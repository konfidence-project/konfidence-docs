import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const project = fileURLToPath(new URL("../", import.meta.url));
const ownSite = "^https?://konfidence[.]cloud([/?#]|$)";

export function linkArguments(mode, directory = path.join(project, ".vitepress/dist"), {
  readme = path.join(project, "README.md"), cache = true
} = {}) {
  if (!["internal", "readme", "external"].includes(mode)) {
    throw new Error("Choose internal, readme, or external link checking.");
  }
  const root = path.resolve(directory);
  if (!existsSync(path.join(root, "index.html"))) {
    throw new Error("The built site is missing. Run pnpm build before checking links.");
  }
  readme = path.resolve(readme);
  if (mode !== "internal" && !existsSync(readme)) {
    throw new Error(`The README is missing: ${readme}`);
  }
  const args = ["--config", path.join(project, "lychee.toml"), "--root-dir",
    mode === "readme" ? path.dirname(readme) : root];
  if (mode !== "external") {
    // Check absolute links to our domain against this build, not the deployed site.
    args.push("--offline", "--remap", `${ownSite} ${pathToFileURL(root).href}$1`);
    if (mode === "readme") {
      // GitHub also renders directories such as LICENSES without a website index.
      args.push("--index-files", "index.html,README.md,.");
    }
  } else {
    // Own-site targets are covered offline. Remote fragments may be generated by JS.
    args.push("--scheme", "http", "--scheme", "https", "--exclude", ownSite,
      "--include-fragments=none");
    if (cache) args.push("--cache");
  }
  args.push("--");
  if (mode !== "readme") args.push(`${root.replaceAll(path.sep, "/")}/**/*.html`);
  if (mode !== "internal") args.push(readme);
  return args;
}

// The official action accepts a shell argument string; quote each argument literally.
export function shellArguments(args) {
  return args.map(arg => `'${arg.replaceAll("'", "'\\''")}'`).join(" ");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const [mode = "internal", output] = process.argv.slice(2);
    if (process.argv.length > 4 || (output && output !== "--github-args")) {
      throw new Error("Usage: node scripts/check-links.mjs [internal|readme|external] [--github-args]");
    }
    // PRs and pushes check the current response, not a result from an earlier run.
    const cache = !["pull_request", "push"].includes(process.env.GITHUB_EVENT_NAME);
    const args = linkArguments(mode, undefined, { cache });
    if (output) {
      console.log(`${mode}=${shellArguments(args)}`);
    } else {
      // Keep the local internal command complete even when the site has findings.
      for (const check of mode === "internal" ? ["internal", "readme"] : [mode]) {
        const result = spawnSync("lychee", linkArguments(check, undefined, { cache }), { stdio: "inherit" });
        if (result.error) {
          throw new Error("Could not start lychee. Install it as described in the README.", { cause: result.error });
        }
        const code = result.status ?? 1;
        if (code !== 0) process.exitCode = code;
        if (![0, 2].includes(code)) break;
      }
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
