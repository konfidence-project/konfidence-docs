import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const project = fileURLToPath(new URL("../", import.meta.url));
const ownSite = "^https?://konfidence[.]cloud([/?#]|$)";

export function linkArguments(mode, directory = path.join(project, ".vitepress/dist")) {
  if (!["internal", "external"].includes(mode)) {
    throw new Error("Choose internal or external link checking.");
  }
  const root = path.resolve(directory);
  if (!existsSync(path.join(root, "index.html"))) {
    throw new Error("The built site is missing. Run pnpm build before checking links.");
  }
  const args = ["--config", path.join(project, "lychee.toml"), "--root-dir", root];
  if (mode === "internal") {
    // Check absolute links to our domain against this build, not the deployed site.
    args.push("--offline", "--remap", `${ownSite} ${pathToFileURL(root).href}$1`);
  } else {
    // Own-site targets are covered offline. Remote fragments may be generated by JS.
    args.push("--scheme", "http", "--scheme", "https", "--exclude", ownSite,
      "--include-fragments=none", "--cache");
  }
  args.push("--", `${root.replaceAll(path.sep, "/")}/**/*.html`);
  return args;
}

// The official action accepts a shell argument string; quote each argument literally.
export function shellArguments(args) {
  return args.map(arg => `'${arg.replaceAll("'", "'\\''")}'`).join(" ");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const [mode = "internal", output] = process.argv.slice(2);
    if (process.argv.length > 4 || (output && output !== "--github-args")) {
      throw new Error("Usage: node scripts/check-links.mjs [internal|external] [--github-args]");
    }
    const args = linkArguments(mode);
    if (output) {
      console.log(`${mode}=${shellArguments(args)}`);
    } else {
      const result = spawnSync("lychee", args, { stdio: "inherit" });
      if (result.error) {
        throw new Error("Could not start lychee. Install it as described in the README.", { cause: result.error });
      }
      process.exitCode = result.status ?? 1;
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
